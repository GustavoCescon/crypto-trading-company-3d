import { test,expect } from '@playwright/test'
test('navigation stays responsive between the office, operations, and research',async({page})=>{
  await page.goto('/',{waitUntil:'domcontentloaded'})
  await page.locator('.rail button').nth(1).click()
  await expect(page.getByRole('heading',{name:'Cada operação, rastreável.'})).toBeVisible()
  await expect(page.getByRole('button',{name:/Posições/})).toBeVisible()
  await page.locator('.rail button').nth(2).click()
  await expect(page.getByRole('heading',{name:'Teste a hipótese, não a sorte.'})).toBeVisible()
  await page.locator('.rail button').nth(0).click()
  await expect(page.getByTestId('office')).toBeVisible()
})
test('office renders WebGL and selects real backend agents',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/',{waitUntil:'domcontentloaded'})
  await expect(page.getByRole('heading',{name:'Seu escritório, em movimento.'})).toBeVisible()
  await expect(page.getByTestId('office').locator('canvas')).toBeVisible()
  await expect(page.getByText(/8 DEPARTAMENTOS · \d+ AGENTES LÓGICOS/)).toBeVisible()
  await expect(page.getByText('Ao vivo',{exact:true})).toBeVisible({timeout:30000})
  await page.getByRole('button').filter({hasText:'Sofia'}).click()
  await expect(page.getByText('AGENTE SELECIONADO')).toBeVisible()
  await expect(page.getByRole('heading',{name:'Sofia'})).toBeVisible()
  expect(errors).toEqual([])
  await page.screenshot({path:'test-results/office.png',fullPage:true})
})
test('snapshot and live socket contain authoritative data',async({page,request})=>{
  const response=await request.get('/api/v1/snapshot');expect(response.ok()).toBeTruthy()
  const snapshot=await response.json();expect(snapshot.simulation).toBe(true)
  expect(snapshot.agents.length).toBeGreaterThan(0)
  const model=await request.get('/models/traders.glb');expect(model.ok()).toBeTruthy()
  const bytes=await model.body();expect(bytes.subarray(0,4).toString()).toBe('glTF');expect(bytes.byteLength).toBeLessThan(500_000)
  await page.goto('/',{waitUntil:'domcontentloaded'})
  const value=await page.evaluate(()=>new Promise<{type:string,schema_version:number}>((resolve,reject)=>{const socket=new WebSocket(`ws://${location.host}/api/v1/ws`);const timer=setTimeout(()=>{socket.close();reject(new Error('socket timeout'))},15000);socket.onmessage=e=>{const v=JSON.parse(e.data);if(v.type==='snapshot'){clearTimeout(timer);socket.close();resolve(v)}}}))
  expect(value.type).toBe('snapshot');expect(value.schema_version).toBe(1)
})
